-- CuidaMais | H2 2.x. Executar como administrador no banco local acadêmico.
CREATE TABLE IF NOT EXISTS usuario (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL CHECK (TRIM(nome) <> ''),
    email VARCHAR(160) NOT NULL UNIQUE,
    senha_hash VARCHAR(255) NOT NULL,
    perfil VARCHAR(10) NOT NULL,
    cuidador_id INTEGER REFERENCES usuario(id)
);
ALTER TABLE usuario ADD COLUMN IF NOT EXISTS situacao VARCHAR(12) DEFAULT 'ATIVA' NOT NULL
    CHECK (situacao IN ('PENDENTE','ATIVA','ENCERRADA'));
ALTER TABLE usuario ADD CONSTRAINT IF NOT EXISTS ck_usuario_perfil CHECK (
    (perfil IN ('CUIDADOR','FAMILIAR') AND cuidador_id IS NULL) OR
    perfil='PACIENTE'
);
ALTER TABLE usuario DROP CONSTRAINT IF EXISTS ck_usuario_tipo_vinculo;
CREATE TABLE IF NOT EXISTS acao_conta (
    token_hash CHAR(64) PRIMARY KEY,
    usuario_id INTEGER NOT NULL REFERENCES usuario(id),
    tipo VARCHAR(8) NOT NULL CHECK(tipo IN ('ATIVAR','EMAIL','SENHA')),
    email VARCHAR(160) NOT NULL,
    expira TIMESTAMP NOT NULL,
    UNIQUE(usuario_id,tipo)
);
CREATE TABLE IF NOT EXISTS vinculo_familiar (
    paciente_id INTEGER NOT NULL REFERENCES usuario(id),
    familiar_id INTEGER NOT NULL REFERENCES usuario(id),
    PRIMARY KEY (paciente_id, familiar_id),
    CHECK (paciente_id <> familiar_id)
);
CREATE TABLE IF NOT EXISTS lembrete (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id INTEGER NOT NULL REFERENCES usuario(id),
    titulo VARCHAR(150) NOT NULL CHECK (TRIM(titulo) <> ''),
    categoria VARCHAR(20) NOT NULL CHECK (categoria IN ('Alimentação','Medicamento','Higiene','Atividade')),
    agendado TIMESTAMP NOT NULL,
    status VARCHAR(12) DEFAULT 'PENDENTE' NOT NULL CHECK (status IN ('PENDENTE','ADIADO','CONFIRMADO')),
    confirmado_em TIMESTAMP,
    CHECK ((status='CONFIRMADO') = (confirmado_em IS NOT NULL))
);
ALTER TABLE lembrete ADD COLUMN IF NOT EXISTS aviso_em TIMESTAMP;
ALTER TABLE lembrete ADD COLUMN IF NOT EXISTS reaviso_em TIMESTAMP;
ALTER TABLE lembrete ADD COLUMN IF NOT EXISTS alerta_em TIMESTAMP;
ALTER TABLE lembrete ADD COLUMN IF NOT EXISTS instrucao VARCHAR(500);
ALTER TABLE lembrete ADD COLUMN IF NOT EXISTS autor_id INTEGER REFERENCES usuario(id);
CREATE TABLE IF NOT EXISTS programacao (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id INTEGER NOT NULL REFERENCES usuario(id),
    revisao INTEGER NOT NULL DEFAULT 1,
    ativa BOOLEAN NOT NULL DEFAULT TRUE,
    proxima TIMESTAMP
);
CREATE TABLE IF NOT EXISTS voz (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mp3 BLOB NOT NULL
);
CREATE TABLE IF NOT EXISTS versao_rotina (
    programa INTEGER NOT NULL REFERENCES programacao(id),
    revisao INTEGER NOT NULL,
    autor INTEGER REFERENCES usuario(id),
    alterada_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    acao VARCHAR(12) NOT NULL,
    titulo VARCHAR(150) NOT NULL,
    categoria VARCHAR(20) NOT NULL,
    inicio TIMESTAMP NOT NULL,
    repeticao VARCHAR(8) NOT NULL CHECK(repeticao IN ('UNICA','DIARIA','SEMANAL')),
    dias VARCHAR(7) NOT NULL,
    instrucao VARCHAR(500),
    voz_id INTEGER REFERENCES voz(id),
    PRIMARY KEY(programa,revisao)
);
ALTER TABLE lembrete ADD COLUMN IF NOT EXISTS programa INTEGER;
ALTER TABLE lembrete ADD COLUMN IF NOT EXISTS revisao INTEGER;
ALTER TABLE lembrete ADD COLUMN IF NOT EXISTS previsto TIMESTAMP;
ALTER TABLE lembrete ADD COLUMN IF NOT EXISTS disparado_em TIMESTAMP;
ALTER TABLE lembrete ADD COLUMN IF NOT EXISTS redisparado_em TIMESTAMP;
ALTER TABLE lembrete ADD COLUMN IF NOT EXISTS entrega VARCHAR(24) DEFAULT 'SEM_CONFIRMACAO' NOT NULL;
ALTER TABLE lembrete ADD CONSTRAINT IF NOT EXISTS fk_versao FOREIGN KEY(programa,revisao) REFERENCES versao_rotina(programa,revisao);
CREATE UNIQUE INDEX IF NOT EXISTS uq_ocorrencia ON lembrete(programa,previsto);
-- Incorporar cada agendamento anterior como uma programação única, preservando seus IDs.
INSERT INTO programacao(id,paciente_id)
SELECT -l.id,l.paciente_id FROM lembrete l WHERE programa IS NULL AND NOT EXISTS(SELECT 1 FROM programacao p WHERE p.id=-l.id);
INSERT INTO versao_rotina(programa,revisao,autor,acao,titulo,categoria,inicio,repeticao,dias,instrucao)
SELECT -id,1,autor_id,'MIGRADA',titulo,categoria,COALESCE(aviso_em,agendado),'UNICA','',instrucao FROM lembrete l
WHERE programa IS NULL AND NOT EXISTS(SELECT 1 FROM versao_rotina v WHERE v.programa=-l.id);
UPDATE lembrete SET programa=-id,revisao=1,previsto=COALESCE(aviso_em,agendado) WHERE programa IS NULL;
CREATE OR REPLACE VIEW agenda_rotina AS
SELECT l.*, CASE WHEN status='CONFIRMADO' THEN 'CONFIRMADO'
                 WHEN alerta_em IS NOT NULL THEN 'ALERTA'
                 WHEN reaviso_em IS NOT NULL THEN 'PENDENTE'
                 ELSE status END AS estado_atual
FROM lembrete l;
CREATE TABLE IF NOT EXISTS registro_comportamental (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id INTEGER NOT NULL REFERENCES usuario(id),
    categoria VARCHAR(32) NOT NULL,
    intensidade INTEGER NOT NULL CHECK (intensidade BETWEEN 1 AND 5),
    observacao VARCHAR(500) NOT NULL,
    registrado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
ALTER TABLE registro_comportamental ADD COLUMN IF NOT EXISTS autor_id INTEGER REFERENCES usuario(id);
CREATE TABLE IF NOT EXISTS historico (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lembrete_id INTEGER NOT NULL REFERENCES lembrete(id),
    estado VARCHAR(12) NOT NULL,
    registrado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_agenda ON lembrete(paciente_id, agendado);
CREATE TRIGGER IF NOT EXISTS auditar_resposta AFTER UPDATE ON lembrete
FOR EACH ROW AS $$
org.h2.api.Trigger create() {
    return new org.h2.api.Trigger() {
        public void fire(java.sql.Connection c, Object[] anterior, Object[] atual) throws java.sql.SQLException {
            if (anterior[5].equals(atual[5])) return;
            try (var p = c.prepareStatement("INSERT INTO historico(lembrete_id,estado) VALUES(?,?)")) {
                p.setObject(1, atual[0]);
                p.setObject(2, atual[5]);
                p.executeUpdate();
            }
        }
    };
}
$$;
CREATE OR REPLACE VIEW resumo_rotina AS
SELECT paciente_id, estado_atual AS status, COUNT(*) AS total FROM agenda_rotina GROUP BY paciente_id,estado_atual;
