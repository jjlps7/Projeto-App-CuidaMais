GRANT SELECT, INSERT, DELETE ON vinculo_familiar TO rotina_app;
GRANT SELECT, INSERT, DELETE ON acao_conta TO rotina_app;
GRANT UPDATE ON usuario TO rotina_app;
GRANT SELECT, INSERT, UPDATE ON programacao TO rotina_app;
GRANT SELECT, INSERT ON versao_rotina, voz TO rotina_app;
GRANT UPDATE, DELETE ON lembrete TO rotina_app;
GRANT SELECT, INSERT ON historico TO rotina_app;
GRANT SELECT ON agenda_rotina, resumo_rotina TO rotina_app;
GRANT SELECT ON resumo_rotina TO consulta;
